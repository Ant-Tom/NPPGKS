// Новости (макеты «Новости» и «Новость 1–10»).
// Фото: /public/images/news/<slug>.jpg — карточка в списке, /public/images/news/<slug>/ — обложка и галерея.
import { typoDeep } from '~/utils/typo'

export interface NewsSection {
  title?: string
  text: string[]
}

export interface GalleryPhoto {
  src: string
  /** фото на две колонки сетки */
  wide?: boolean
}

export interface NewsItem {
  title: string
  /** карточка в списке */
  image?: string
  /** карточка в списке на две колонки */
  wide?: boolean
  /** нет slug — нет отдельной страницы (карточка не ссылается) */
  slug?: string
  year?: string
  /** фото 600×750 слева от текста; нет — серая заглушка, как в макете */
  cover?: string
  /** абзацы справа от обложки */
  lead?: string[]
  /** абзацы в две колонки под обложкой */
  columns?: string[]
  /** подразделы с заголовком */
  sections?: NewsSection[]
  gallery?: GalleryPhoto[]
}

const img = (name: string) => `/images/news/${name}.jpg`

// Сетки галерей из макетов (3 колонки): «квадрат + широкое, затем три квадрата»
// и «квадрат + широкое, затем широкое + квадрат»
const galleryA = (slug: string, files: string[]): GalleryPhoto[] =>
  files.map((f, i) => ({ src: img(`${slug}/${f}`), wide: i === 1 }))
const galleryB = (slug: string, files: string[]): GalleryPhoto[] =>
  files.map((f, i) => ({ src: img(`${slug}/${f}`), wide: i === 1 || i === 2 }))

